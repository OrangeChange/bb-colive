import assert from 'node:assert/strict';
import { createRequire } from 'node:module';

const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage();
  await page.goto((process.env.FEED_TEST_URL || 'http://127.0.0.1:1437') + '/tests/fixtures/localFeedReading.html');
  await page.waitForFunction(() => document.querySelector('#frame-status')?.textContent === '就绪');
  const frame = page.frameLocator('iframe[title="延迟滚动容器"]');
  await frame.locator('.scroll-area').evaluate(node => node.remove());
  await page.waitForFunction(() => document.querySelector('#frame-status')?.textContent === '等待', null, { timeout: 2000 });
  await frame.locator('body').evaluate(body => { const node = body.ownerDocument.createElement('div'); node.className = 'scroll-area'; body.append(node); });
  await page.waitForFunction(() => document.querySelector('#frame-status')?.textContent === '就绪', null, { timeout: 2000 });
  const a = page.locator('#a');
  const b = page.locator('#b');
  await a.hover();
  await page.mouse.wheel(0, -600);
  await page.waitForTimeout(300);
  const anchor = async () => a.evaluate(node => {
    const row = [...node.children].find(item => item.getBoundingClientRect().bottom > node.getBoundingClientRect().top);
    return { id: row.dataset.eventId, offset: row.getBoundingClientRect().top - node.getBoundingClientRect().top };
  });
  const before = await anchor();
  await page.getByText('重建a').click();
  await page.waitForTimeout(200);
  assert.deepEqual(await anchor(), before, '列表重建后保持事件锚点');
  await page.getByText('调整a').click();
  await page.waitForTimeout(200);
  assert.deepEqual(await anchor(), before, '行高变化后保持事件锚点');
  await page.waitForTimeout(600);
  await page.getByText('布局滚动a').click();
  await page.waitForTimeout(200);
  assert.deepEqual(await anchor(), before, '布局滚动不覆盖历史位置');
  await page.getByText('载入a').click();
  await page.waitForTimeout(400);
  assert.deepEqual(await anchor(), before, '事件仍保留时短暂卸载不替换锚点');
  await page.getByText('恢复标识a').click();
  await page.waitForTimeout(400);
  assert.deepEqual(await anchor(), before, '事件标识恢复后保持锚点');
  await page.getByText('平移a').click();
  await page.waitForTimeout(200);
  assert.deepEqual(await anchor(), before, '列表平移后保持事件锚点');
  await page.getByText('追加a').click();
  await page.waitForTimeout(200);
  assert.deepEqual(await anchor(), before, '追加不拉回历史位置');
  assert.equal(await b.evaluate(n => n.scrollHeight - n.clientHeight - n.scrollTop), 0, '另一列表仍跟随最新');
  await page.getByText('重播a').click();
  await page.waitForTimeout(200);
  assert.equal(await a.evaluate(n => n.scrollHeight - n.clientHeight - n.scrollTop), 0, '明确重播恢复跟随');
  await a.hover();
  await page.mouse.wheel(0, -600);
  await page.waitForTimeout(200);
  await a.hover();
  await page.mouse.wheel(0, 10000);
  await page.waitForTimeout(300);
  await page.getByText('追加a').click();
  await page.waitForTimeout(200);
  assert.equal(await a.evaluate(n => n.scrollHeight - n.clientHeight - n.scrollTop), 0, '手动回到最新后继续跟随');
  await page.reload();
  await a.hover();
  await page.mouse.wheel(0, -600);
  await page.waitForTimeout(600);
  await page.getByText('清空a', { exact: true }).click();
  await page.getByText('清空b', { exact: true }).click();
  await page.waitForTimeout(400);
  await page.getByText('重填a', { exact: true }).click();
  await page.getByText('重填b', { exact: true }).click();
  await page.waitForTimeout(400);
  assert.ok(await a.evaluate(n => n.scrollHeight - n.clientHeight - n.scrollTop) > 4, '清空后历史页保持阅读意图');
  assert.equal(await b.evaluate(n => n.scrollHeight - n.clientHeight - n.scrollTop), 0, '清空后跟随页继续跟随');
  const c = page.locator('#c'), d = page.locator('#d');
  await c.hover();
  await page.mouse.wheel(0, 600);
  await page.waitForTimeout(600);
  await page.getByText('清空c', { exact: true }).click();
  await page.getByText('清空d', { exact: true }).click();
  await page.waitForTimeout(400);
  await page.getByText('重填c', { exact: true }).click();
  await page.getByText('重填d', { exact: true }).click();
  await page.waitForTimeout(400);
  assert.ok(await c.evaluate(n => n.scrollTop) > 4, '顶部方向清空后历史页保持阅读意图');
  assert.equal(await d.evaluate(n => n.scrollTop), 0, '顶部方向清空后跟随页继续跟随');
  const x = page.locator('#switch-x'), y = page.locator('#switch-y');
  await x.hover(); await page.mouse.wheel(0, -600); await page.waitForTimeout(400);
  const readSwitch = node => node.evaluate(el => { const top = el.getBoundingClientRect().top, row = [...el.children].find(item => item.getBoundingClientRect().bottom > top); return { id: row?.dataset.eventId, offset: row?.getBoundingClientRect().top - top }; });
  const switchBefore = await readSwitch(x);
  await page.getByText('切换x', { exact: true }).click(); await page.waitForTimeout(400);
  assert.deepEqual(await readSwitch(x), switchBefore, '切换容器后保留历史锚点');
  assert.equal(await y.evaluate(el => el.scrollHeight - el.clientHeight - el.scrollTop), 0, '另一列表保持跟随');
  await page.getByText('切换x', { exact: true }).click(); await page.waitForTimeout(400);
  assert.deepEqual(await readSwitch(x), switchBefore, '切回原容器后保留历史锚点');
  await page.reload();
  for (const [selector, delta, direction] of [['#a', -300, 'bottom'], ['#c', 300, 'top']]) {
    const list = page.locator(selector);
    await list.evaluate(node => { node.style.height = '1946px'; });
    await page.waitForTimeout(300);
    await list.hover(); await page.mouse.wheel(0, delta); await page.waitForTimeout(400);
    const position = await list.evaluate(node => node.scrollTop);
    assert.ok(direction === 'bottom' ? position < 4 : position > 50, '真实滚轮进入短列表的历史端');
    await list.evaluate(node => { node.style.height = '1996px'; }); await page.waitForTimeout(400);
    await list.evaluate(node => { node.style.height = '1946px'; }); await page.waitForTimeout(400);
    assert.ok(Math.abs(await list.evaluate(node => node.scrollTop) - position) <= 4, `${direction}方向短列表重排后保持历史位置`);
  }
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#frame-status')?.textContent === '就绪');
  for (const [selector, historyDelta, latestDelta, name, direction] of [['#a', -600, 300, 'a', 'bottom'], ['#c', 600, -300, 'c', 'top']]) {
    const list = page.locator(selector);
    await list.hover(); await page.mouse.wheel(0, historyDelta); await page.waitForTimeout(400);
    await page.getByText(`清空${name}`, { exact: true }).click(); await page.waitForTimeout(300);
    await list.evaluate(node => { node.dataset.wheelObserved = '0'; node.addEventListener('wheel', () => { node.dataset.wheelObserved = '1'; }, { once: true }); });
    await list.hover(); await page.mouse.wheel(0, latestDelta); await page.waitForTimeout(300);
    await page.waitForFunction(selector => document.querySelector(selector)?.dataset.wheelObserved === '1', selector);
    await page.getByText(`重填${name}`, { exact: true }).click(); await page.waitForTimeout(400);
    const state = await list.evaluate(node => ({ top: node.scrollTop, max: node.scrollHeight - node.clientHeight }));
    assert.ok(direction === 'top' ? state.top <= 4 : state.max - state.top <= 4, `${direction}方向空列表滚向最新后继续跟随`);
  }
  console.log('本地阅读位置：重建、行高变化、追加、独立跟随和恢复跟随通过');
} finally {
  await browser.close();
}
