import {mkdirSync} from 'node:fs';
import {chromium} from 'playwright';
import assert from 'node:assert/strict';
mkdirSync('.superpowers/software-updates',{recursive:true});
const b=await chromium.launch({channel:'msedge',headless:true});
try {
 const p=await b.newPage({viewport:{width:900,height:760}}),errors=[];
 p.on('pageerror',e=>errors.push(e.message));
 await p.goto(`${process.env.BB_COLIVE_TEST_BASE_URL??'http://127.0.0.1:1420'}/tests/fixtures/softwareUpdate.html`);
 await p.getByRole('button',{name:'检查更新',exact:true}).click();
 await p.getByRole('button',{name:'下载更新',exact:true}).waitFor();
 await p.evaluate(()=>window.updateTest.controls.checkFailure=true);
 await p.getByRole('radiogroup',{name:'更新线路',exact:true}).getByText('国外',{exact:true}).click();
 await p.getByRole('button',{name:'重试检查',exact:true}).waitFor();
 assert.equal(await p.evaluate(()=>window.updateTest.state.getState().offer),null);
 assert.equal(await p.getByRole('button',{name:'重试下载',exact:true}).count(),0);
 await p.evaluate(()=>window.updateTest.controls.checkFailure=false);
 await p.getByRole('button',{name:'重试检查',exact:true}).click();
 await p.getByRole('button',{name:'下载更新',exact:true}).waitFor();
 await p.evaluate(()=>window.updateTest.state.setState({phase:'current',offer:null,manualVersion:'v1.2.0'}));
 assert.match(await p.getByRole('link',{name:'前往下载页'}).getAttribute('href'),/tag\/v1.2.0$/);
 await p.evaluate(()=>window.updateTest.state.setState({phase:'available',offer:window.updateTest.offer,manualVersion:null}));
 await p.getByRole('button',{name:'关于 BB CoLive',exact:true}).click();
 await p.getByRole('dialog').waitFor();
 await p.getByRole('button',{name:'关闭关于',exact:false}).click();
 await p.getByRole('button',{name:'下载更新',exact:true}).click();
 await p.getByRole('button',{name:'取消下载',exact:true}).click();
 await p.getByRole('button',{name:'下载更新',exact:true}).waitFor();
 await p.getByRole('button',{name:'下载更新',exact:true}).click();
 await p.getByRole('button',{name:'重启并更新',exact:true}).waitFor();
 const frame=await p.locator('.colive-logo [id$="tv-layer"]').elementHandle();
 await p.evaluate(()=>window.updateTest.state.setState({phase:'failed',error:'更新包下载不完整，请重试'}));
 assert(await frame.evaluate(e=>e.isConnected));
 await p.getByRole('button',{name:'重试下载',exact:true}).waitFor();
 await p.screenshot({path:'.superpowers/software-updates/settings-light.png'});
 await p.evaluate(()=>window.updateTest.theme.getState().setMode('dark'));
 await p.screenshot({path:'.superpowers/software-updates/settings-dark.png'});
 await p.setViewportSize({width:360,height:760});
 assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await p.screenshot({path:'.superpowers/software-updates/settings-narrow.png'});
 await p.emulateMedia({reducedMotion:'reduce'});
 assert.equal(await p.locator('[data-face]').first().evaluate(e=>getComputedStyle(e).transitionDuration),'0s');
 assert.deepEqual(errors,[]);
 console.log('更新设置：检查、关于、取消、重新下载、就绪、重试、固定品牌外框、深浅色和窄窗通过。');
} finally {await b.close();}
