import assert from "node:assert/strict";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ headless: true, channel: "msedge" });
try {
  const page = await browser.newPage();
  await page.goto(`${process.env.PREVIEW_TEST_URL || "http://localhost:1420"}/tests/fixtures/nativePreviewSwitch.html`);
  const result = await page.evaluate(async () => {
    const ReactModule = await import("/@id/react");
    const React = ReactModule.default ?? ReactModule;
    const ReactDom = await import("/@id/react-dom/client");
    const createRoot = ReactDom.createRoot ?? ReactDom.default?.createRoot;
    const { LaplaceEvent, LaplaceEventSurface } = await import("/src/compat/laplace/components.tsx");
    const { createLaplaceBaseCss } = await import("/src/compat/laplace/theme.ts");
    const { createDefaultCompatibleThemeSettings } = await import("/src/themes/compatThemeSettings.ts");
    await import("/src/compat/laplace/register.tsx");
    const { getCompatibleThemeEditingSurface } = await import("/src/components/CompatibleThemePreview.tsx");
    const { createCompatibleThemeModeAdapter } = await import("/src/themes/themeModeAdapters.ts");
    const settings = createDefaultCompatibleThemeSettings("laplace");
    const sourceCss = (await import("/src/compat/laplace/source.css?raw")).default;
    const mount = document.createElement("div"); mount.className = "laplace-theme-root"; document.body.append(mount);
    const root = createRoot(mount);
    root.render(React.createElement(LaplaceEvent, { event: { id: "m", msgType: 0, roomId: 1, ts: 1700000000000, user: { uid: "1", uname: "用户", avatar: "", guardLevel: 0 }, text: "正文||剧透||" }, placement: "main", settings }));
    await new Promise(resolve => setTimeout(resolve, 100));
    const event = mount.querySelector(".event--message"); const spoiler = mount.querySelector(".spoiler");
    const style = document.createElement("style"); style.textContent = `${sourceCss}\n${createLaplaceBaseCss({ ...settings, baseFontSize: 24 })}.fixed{gap:.25rem;font-size:17px}`; document.head.append(style);
    event.classList.add("fixed"); const computed = getComputedStyle(event);
    const computedValues = { padding: computed.padding, gap: computed.gap, fontSize: computed.fontSize };
    const avatar24 = getComputedStyle(mount.querySelector("[data-slot='avatar']")).width;
    const renderEvent = async (event, options = {}) => { root.render(React.createElement(options.surface ? LaplaceEventSurface : LaplaceEvent, { event, placement: options.placement ?? "main", settings: options.settings ?? settings, mode: options.mode ?? "obs" })); await new Promise(resolve => setTimeout(resolve, 50)); };
    const eventBase = { roomId: 1, ts: 1700000000000, user: { uid: "1", uname: "用户", avatar: "", guardLevel: 0 } };
    await renderEvent({ ...eventBase, id: "g", msgType: 1, gift: { id: 1, name: "礼物", count: 1, total: 30000, coinType: "gold" } }, { placement: "sticky" });
    await new Promise(resolve => setTimeout(resolve, 50));
    const sticky = mount.querySelector(".laplace-sticky-root"); sticky.click(); await new Promise(resolve => setTimeout(resolve, 50));
    const expanded = sticky.getAttribute("aria-expanded"); const detail = Boolean(mount.querySelector(".laplace-detail-root .event-show-as--normal"));
    const surface = getCompatibleThemeEditingSurface("laplace");
    const themeDocument = createCompatibleThemeModeAdapter("laplace").createBuiltinTheme();
    root.render(surface.renderer({ document: themeDocument, thumbnail: false })); await new Promise(resolve => setTimeout(resolve, 100));
    const registeredRedStart = Boolean(mount.querySelector(".event--red-envelope-start"));
    await renderEvent({ ...eventBase, id: "dashboard", msgType: 0, text: "正文" }, { mode: "dashboard", surface: true });
    const dashboardText = mount.textContent;
    const formalScene = Boolean(mount.querySelector(".events-list-wrap.scene-default .event--message"));
    await renderEvent({ ...eventBase, id: "gift", msgType: 1, gift: { id: 1, name: "礼物", count: 1, total: 30000, coinType: "gold" } }, { settings: { ...settings, baseFontSize: 24 } });
    const giftAvatar = getComputedStyle(mount.querySelector("[data-slot='avatar']")).width;
    await renderEvent({ ...eventBase, id: "sc", msgType: 2, sc: { price: 30, message: "醒目留言", duration: 60 } }, { settings: { ...settings, baseFontSize: 24 } });
    const scAvatar = getComputedStyle(mount.querySelector("[data-slot='avatar']")).width;
    return { event: Boolean(event), username: true, spoiler: Boolean(spoiler), ...computedValues, avatar24, expanded, detail, registeredRedStart, registeredSurface: Boolean(surface), dashboardText, formalScene, giftAvatar, scAvatar };
  });
  assert.equal(result.event, true); assert.equal(result.username, true); assert.equal(result.spoiler, true);
  assert.equal(result.padding, "3px 12px"); assert.equal(result.gap, "4px"); assert.equal(result.fontSize, "17px");
  assert.equal(result.avatar24, "36px"); assert.equal(result.expanded, "true"); assert.equal(result.detail, true);
  assert.equal(result.registeredSurface, true); assert.equal(result.registeredRedStart, true);
  assert.match(result.dashboardText, /用户/); assert.equal(result.formalScene, true);
  assert.equal(result.giftAvatar, "48px"); assert.equal(result.scAvatar, "60px");
  console.log(JSON.stringify(result));
} finally { await browser.close(); }
